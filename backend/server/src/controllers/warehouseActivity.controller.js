import { ROLES } from "../constants/roles.js";

import {
  warehouseActivityQuerySchema,
} from "../validators/warehouseActivity.validator.js";

import warehouseActivityService
  from "../services/warehouseActivity.service.js";

import { ApiResponse }
  from "../utils/apiResponse.js";

import { ApiError }
  from "../utils/apiError.js";

import { asyncHandler }
  from "../utils/asyncHandler.js";

const companyIdForRequest = (req) => {
  const authCompanyId =
    req.auth?.companyId ||
    req.user?.companyId?._id ||
    req.user?.companyId;

  if (req.user?.role !== ROLES.SUPER_ADMIN) {
    if (!authCompanyId) {
      throw new ApiError(
        403,
        "Company context missing"
      );
    }

    return authCompanyId;
  }

  const requestedCompanyId =
    req.query?.companyId ||
    req.body?.companyId ||
    authCompanyId;

  if (!requestedCompanyId) {
    throw new ApiError(
      400,
      "companyId is required for Super Admin"
    );
  }

  return requestedCompanyId;
};

function validate(schema, source) {
  const { value, error } = schema.validate(
    source,
    {
      abortEarly: false,
      stripUnknown: true,
    }
  );

  if (error) {
    throw new ApiError(
      400,
      error.details[0].message,
      error.details
    );
  }

  return value;
}

export const getWarehouseActivity =
  asyncHandler(async (req, res) => {
    const query = validate(
      warehouseActivityQuerySchema,
      req.query
    );

    const result =
      await warehouseActivityService.listActivity({
        companyId:
          companyIdForRequest(req),
        query,
      });

    res.status(200).json(
      new ApiResponse(
        200,
        result,
        "Activity fetched successfully"
      )
    );
  });

export const getWarehouseActivitySummary =
  asyncHandler(async (req, res) => {
    const result =
      await warehouseActivityService.getSummary({
        companyId:
          companyIdForRequest(req),
      });

    res.status(200).json(
      new ApiResponse(
        200,
        result,
        "Activity summary fetched successfully"
      )
    );
  });